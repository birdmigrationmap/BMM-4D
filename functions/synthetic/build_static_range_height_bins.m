function bins = build_static_range_height_bins(g, range_edges_km, height_edges_m)
%BUILD_STATIC_RANGE_HEIGHT_BINS Build shared range-height bin indices.

range_centers_km = range_edges_km(1:end-1) + diff(range_edges_km) / 2;
height_centers_m = height_edges_m(1:end-1) + diff(height_edges_m) / 2;

x_grid = g.x(:) - g.x(end) / 2;
y_grid = g.y(:) - g.y(end) / 2;
[X_grid, Y_grid, Z_grid] = ndgrid(x_grid, y_grid, g.z(:));

range_bin = discretize(hypot(X_grid(:), Y_grid(:)) ./ 1000, range_edges_km);
height_bin = discretize(Z_grid(:), height_edges_m);
valid_vector = ~isnan(range_bin) & ~isnan(height_bin);

bins = struct( ...
    "range_edges_km", range_edges_km, ...
    "height_edges_m", height_edges_m, ...
    "range_centers_km", range_centers_km, ...
    "height_centers_m", height_centers_m, ...
    "bin_size", [numel(range_centers_km) numel(height_centers_m)], ...
    "valid_vector", valid_vector, ...
    "valid_mask", reshape(valid_vector, g.sz), ...
    "bin_id", sub2ind([numel(range_centers_km) numel(height_centers_m)], range_bin(valid_vector), height_bin(valid_vector)), ...
    "n_bin", numel(range_centers_km) * numel(height_centers_m));
end
